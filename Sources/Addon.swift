import Foundation

/// 이 저장소에 없는 애드온이 스스로를 꽂는 자리.
///
/// 이 파일은 **MIT 다.** 여기 있는 것은 «자리» 뿐이고 «내용» 은 `Addon/Sources/` 에 있다.
/// 그쪽은 이 저장소의 일부가 아니다 (`.gitignore`). 그래서 clone 해 온 사람이 받는 것은
/// 빈 자리뿐이고, 빌드하면 애드온 없는 판이 나온다.
///
/// **비어 있는 것이 정상이다.** 애드온 없는 판은 덜 만든 앱이 아니라 그것으로 온전한
/// 앱이다. 이 등록부가 비었다고 화면에 «없음» 이나 «잠김» 을 그리지 않는다 — 없는 것을
/// 보여 주면 그 판을 쓰는 사람이 매번 제 앱이 모자란다는 말을 듣게 된다.
///
/// ## 왜 런타임 스위치가 아니라 소스를 가르는가
///
/// 이 앱은 `./build.sh` 가 공식 설치 경로다 (README 가 직접 안내한다). 그래서 «켜졌나»
/// 를 묻는 검사는 **다섯 줄 지우면 끝난다.** 반면 소스가 아예 없으면 그 기능은 존재하지
/// 않는다 — 지울 것이 없다. 가를 곳은 조건문이 아니라 파일이다.
///
/// 라이선스도 파일 단위로 붙으므로 이쪽이 경계로서도 깨끗하다.
enum Addon {

    /// 애드온이 더하는 세션 출처.
    ///
    /// `CompositeSource` 가 배열을 받으므로 여기 꽂힌 것은 **화면 코드를 한 줄도 고치지
    /// 않고** 목록에 섞인다. 출처를 늘릴 생각으로 만들어 둔 자리가 그대로 경계가 되었다.
    static var extraSources: [SessionSource] = []

    /// 애드온이 꽂혔는가.
    ///
    /// **표시를 가르는 데만 쓴다.** 기능을 막는 데 쓰지 않는다 — 막을 기능은 애초에
    /// 이 빌드에 들어 있지 않다. 이 값으로 무언가를 잠그기 시작하면 그 순간
    /// 「소스를 안 준다」는 경계가 「스위치 하나」로 내려앉는다.
    static var isActive = false
}
