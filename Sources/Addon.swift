import Foundation
// 탭 등록부가 `AnyView` 를 받으므로 여기까지 SwiftUI 가 따라온다. 이 앱은 어차피 GUI
// 번들이고 배포 대상이 macOS 13 이라 더 드는 값은 없다.
import SwiftUI

/// 이 저장소에 없는 애드온이 스스로를 꽂는 자리.
///
/// 이 파일은 **MIT 다.** 여기 있는 것은 «자리» 뿐이고 «내용» 은 `Addon/Sources/` 에 있다.
/// 그쪽은 이 저장소의 일부가 아니다 (`.gitignore`). 그래서 clone 해 온 사람이 받는 것은
/// 빈 자리뿐이고, 빌드하면 애드온 없는 판이 나온다.
///
/// **비어 있는 것이 정상이다.** 애드온 없는 판은 덜 만든 앱이 아니라 그것으로 온전한
/// 앱이다. 이 등록부가 비었다고 화면에 «없음» 이나 «잠김» 을 그리지 않는다 — 없는 것을
/// 보여 주면 그 판을 쓰는 사람이 매번 제 앱이 모자란다는 말을 듣게 된다.
///
/// ## 왜 런타임 스위치가 아니라 소스를 가르는가
///
/// 이 앱은 `./build.sh` 가 공식 설치 경로다 (README 가 직접 안내한다). 그래서 «켜졌나»
/// 를 묻는 검사는 **다섯 줄 지우면 끝난다.** 반면 소스가 아예 없으면 그 기능은 존재하지
/// 않는다 — 지울 것이 없다. 가를 곳은 조건문이 아니라 파일이다.
///
/// 라이선스도 파일 단위로 붙으므로 이쪽이 경계로서도 깨끗하다.
enum Addon {

    /// 애드온이 더하는 세션 출처.
    ///
    /// `CompositeSource` 가 배열을 받으므로 여기 꽂힌 것은 **화면 코드를 한 줄도 고치지
    /// 않고** 목록에 섞인다. 출처를 늘릴 생각으로 만들어 둔 자리가 그대로 경계가 되었다.
    static var extraSources: [SessionSource] = []

    /// 애드온이 명령줄을 가로채는 자리.
    ///
    /// `main.swift` 가 아는 명령을 모두 지나온 뒤에 차례로 물어본다. 처리한 쪽이 `true` 를
    /// 내면 거기서 끝난다.
    ///
    /// **이 저장소는 무슨 명령이 오는지 모른다.** 알면 그 이름이 곧 애드온이 무엇을 하는지가
    /// 되므로, 가로챌 수 있다는 사실만 두고 내용은 `Addon/` 안에 둔다.
    static var extraCommands: [([String]) -> Bool] = []

    /// 애드온이 줄에 덧붙이는 글 한 조각. `nil` 이면 아무것도 안 붙는다.
    ///
    /// 줄을 짜는 쪽은 이 글이 무엇인지 모르고 자리만 내준다. 칸을 새로 만들지 않고
    /// 한 조각으로 받는 것도 같은 이유다 — 칸 이름이 늘면 그 이름이 말을 한다.
    ///
    /// **폭을 정하지 않는다** (`cells: 0`). 정해 두면 글이 없는 목록에서도 그 폭만큼
    /// 자리를 지켜, 애드온이 없는 판의 줄이 까닭 없이 벌어진다.
    static var rowAnnotation: ((Session) -> String?)?

    /// 애드온이 설정창에 두는 제 탭. `nil` 이면 탭이 아예 안 생긴다.
    ///
    /// 앞의 등록부들은 **값**을 받았는데 이것만 **화면**을 받는다. `AnyView` 로 감싸므로
    /// 이 저장소는 그 안에 무엇이 그려지는지 끝까지 모른다 — 탭 이름조차 애드온이 내놓는다.
    ///
    /// 애드온이 늘면 각자 제 방이 필요하다. 남의 탭에 한 줄씩 끼어들면 그 탭이 곧
    /// 아무의 것도 아니게 된다.
    static var settingsTab: (() -> AnyView)?

    /// 그 탭에 붙일 이름. 탭이 서려면 이것도 있어야 한다.
    static var settingsTabLabel: String?

    /// 애드온이 툴팁에 보태는 글. 여러 줄이어도 되고 `nil` 이면 아무것도 안 붙는다.
    ///
    /// 줄에 붙이는 `rowAnnotation` 과 **자리가 다르다.** 줄은 한 칸이라 한 조각만 들어가고,
    /// 툴팁은 마우스를 올린 한 줄에만 뜨므로 길어도 된다. 곁눈으로 보는 것과 자세히 보는
    /// 것을 한 등록부로 받으면 둘 중 하나는 반드시 맞지 않는다.
    ///
    /// **메뉴와 상시 창이 같은 글을 쓴다** — 둘 다 `SessionRowStyle.tooltip` 을 거친다.
    static var rowDetail: ((Session) -> String?)?

    /// 애드온이 여는 제 창의 알맹이. `nil` 이면 메뉴 항목이 아예 안 생긴다.
    ///
    /// 설정 탭(`settingsTab`)과 나란한 자리이나 **창을 따로 내는 데는 까닭이 있다.**
    /// 설정은 고치고 닫는 자리라, 켜 두고 보는 것을 거기 밀어 넣으면 그것을 보는 내내
    /// 설정창을 붙잡고 있어야 한다. 무엇을 켜 두고 보는지는 이 저장소가 알 바가 아니다.
    ///
    /// **지금 세션을 당겨 읽는 손을 함께 건넨다.** 애드온이 스스로 훑지 못하게 하려는
    /// 것이다 — 이 앱은 이미 몇 초마다 훑고 있고, 한 번 더 훑으면 재는 값이 두 배로 들
    /// 뿐 아니라 쓰임새 기록이 **표본 사이 간격을 시간의 단위로 쓰기 때문에** 그 단위가
    /// 뒤틀린다 (`StatsRecorder`). 설정창이 이미 같은 손을 받아 쓰고 있다.
    static var extraWindowContent: ((@escaping () -> [Session]) -> AnyView)?

    /// 그 창에 붙일 이름. 메뉴 항목의 글이자 창 제목이 된다. 이것도 있어야 창이 선다.
    ///
    /// 이름을 이 저장소에 박아 두지 않는 것은 `settingsTabLabel` 과 같은 까닭이다 —
    /// 박아 두는 순간 그 글이 곧 애드온이 무엇을 하는지가 된다.
    static var extraWindowLabel: String?

    /// 애드온이 꽂혔는가.
    ///
    /// **표시를 가르는 데만 쓴다.** 기능을 막는 데 쓰지 않는다 — 막을 기능은 애초에
    /// 이 빌드에 들어 있지 않다. 이 값으로 무언가를 잠그기 시작하면 그 순간
    /// 「소스를 안 준다」는 경계가 「스위치 하나」로 내려앉는다.
    static var isActive = false
}
